-- Traitements en masse : import d'un export Apogée ou extraction de la vue Oracle
create table batch_jobs (
    id               uuid primary key,
    document_type    varchar(40)   not null,
    source           varchar(20)   not null,
    description      varchar(500)  not null,
    status           varchar(30)   not null,
    total            integer       not null,
    succeeded        integer       not null default 0,
    failed           integer       not null default 0,
    client_id        varchar(100)  not null,
    issued_by_id     varchar(100)  not null,
    issued_by_name   varchar(200)  not null,
    issued_by_source varchar(20)   not null,
    purpose          varchar(40),
    created_at       timestamp with time zone not null,
    started_at       timestamp with time zone,
    finished_at      timestamp with time zone,
    version          bigint        not null default 0
);

create index idx_batch_jobs_status on batch_jobs (status);

create table batch_items (
    id            bigint generated by default as identity primary key,
    job_id        uuid          not null references batch_jobs (id),
    item_key      varchar(200)  not null,
    cne           varchar(32),
    source_lines  varchar(200)  not null,
    status        varchar(30)   not null,
    document_id   uuid,
    error         varchar(2000),
    -- Demande à traiter (JSON) ; effacée une fois l'élément traité (minimisation des données)
    payload       varchar(200000)
);

create index idx_batch_items_job on batch_items (job_id, status);
