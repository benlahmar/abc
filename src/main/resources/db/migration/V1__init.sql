create table documents (
    id                uuid primary key,
    verification_code varchar(32)  not null unique,
    type              varchar(40)  not null,
    status            varchar(20)  not null,
    student_cne       varchar(32)  not null,
    student_name      varchar(210) not null,
    academic_year     varchar(9)   not null,
    semester          varchar(10),
    client_id         varchar(100) not null,
    idempotency_key   varchar(100),
    request_hash      varchar(64)  not null,
    sha256            varchar(64)  not null,
    storage_key       varchar(200) not null,
    signature_level   varchar(40)  not null,
    signer_subject    varchar(500) not null,
    created_at        timestamp with time zone not null,
    signed_at         timestamp with time zone not null,
    revoked_at        timestamp with time zone,
    revocation_reason varchar(500),
    version           bigint       not null default 0,
    constraint uk_documents_idempotency unique (client_id, idempotency_key)
);

create index idx_documents_sha256 on documents (sha256);
create index idx_documents_student on documents (student_cne);

create table audit_events (
    id            bigint generated by default as identity primary key,
    event_type    varchar(50)   not null,
    document_id   uuid,
    actor         varchar(150)  not null,
    details       varchar(1000),
    created_at    timestamp with time zone not null,
    previous_hash varchar(64)   not null,
    hash          varchar(64)   not null
);

create index idx_audit_document on audit_events (document_id);

create table audit_chain_head (
    id        integer primary key,
    last_hash varchar(64) not null
);

