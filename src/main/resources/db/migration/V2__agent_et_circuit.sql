-- Traçabilité : personne qui a établi le document
alter table documents add column issued_by_id varchar(100);
alter table documents add column issued_by_name varchar(200);
-- AUTHENTICATED : identité issue du jeton de l'agent ; DECLARED : déclarée par l'application cliente
alter table documents add column issued_by_source varchar(20);
-- Usage déclaré du document (ex. ETRANGER), utilisable comme condition d'une étape du circuit
alter table documents add column purpose varchar(40);
-- Validation supplémentaire demandée (active les étapes IF_ESCALATED)
alter table documents add column escalated boolean not null default false;
-- PDF non signé en attente d'approbation
alter table documents add column unsigned_storage_key varchar(200);

-- Un document en attente d'approbation n'est pas encore signé
alter table documents alter column sha256 drop not null;
alter table documents alter column storage_key drop not null;
alter table documents alter column signature_level drop not null;
alter table documents alter column signer_subject drop not null;
alter table documents alter column signed_at drop not null;

update documents set issued_by_id = client_id, issued_by_name = client_id, issued_by_source = 'DECLARED'
where issued_by_id is null;

-- Paramétrage du circuit d'approbation, par type de document (aucune étape = signature immédiate)
create table workflow_steps (
    id             bigint generated by default as identity primary key,
    document_type  varchar(40)  not null,
    step_order     integer      not null,
    name           varchar(100) not null,
    role           varchar(60)  not null,
    condition_type varchar(20)  not null,
    purposes       varchar(500),
    constraint uk_workflow_steps unique (document_type, step_order)
);

-- Étapes d'approbation de chaque document : copie du circuit au moment de la demande,
-- pour qu'un changement de paramétrage n'affecte pas les demandes en cours.
create table document_approvals (
    id              bigint generated by default as identity primary key,
    document_id     uuid         not null references documents (id),
    step_order      integer      not null,
    name            varchar(100) not null,
    role            varchar(60)  not null,
    condition_type  varchar(20)  not null,
    status          varchar(20)  not null,
    decided_by_id   varchar(100),
    decided_by_name varchar(200),
    decided_at      timestamp with time zone,
    comment         varchar(500),
    version         bigint       not null default 0,
    constraint uk_document_approvals unique (document_id, step_order)
);

create index idx_approvals_pending on document_approvals (status, role);
