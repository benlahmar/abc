-- Registre des inscrits : listes importées par filière et par année, utilisées pour délivrer
-- immédiatement les attestations de scolarité demandées en ligne (mode REGISTRY).

create table registry_imports (
    id              uuid primary key,
    academic_year   varchar(9)   not null,
    filiere         varchar(150) not null,
    file_name       varchar(255),
    student_count   integer      not null,
    added           integer      not null,
    removed         integer      not null,
    changed         integer      not null,
    imported_by_id   varchar(100) not null,
    imported_by_name varchar(200) not null,
    imported_at     timestamp with time zone not null
);

create index idx_registry_imports_year on registry_imports (academic_year, filiere, imported_at);

-- Un étudiant figure au plus une fois par année (dans sa filière d'inscription)
create table registry_students (
    id              bigint generated by default as identity primary key,
    academic_year   varchar(9)   not null,
    cne             varchar(32)  not null,
    nom             varchar(100) not null,
    prenom          varchar(100) not null,
    date_naissance  date,
    lieu_naissance  varchar(100),
    filiere         varchar(150) not null,
    niveau          varchar(100) not null,
    import_id       uuid         not null references registry_imports (id),
    -- Bloqué par un agent : plus de délivrance immédiate (la demande va au service)
    blocked_reason  varchar(500),
    blocked_by      varchar(200),
    blocked_at      timestamp with time zone,
    constraint uq_registry_year_cne unique (academic_year, cne)
);

create index idx_registry_students_filiere on registry_students (academic_year, filiere);

-- Note interne pour les agents (ex. « absent du registre »), jamais montrée à l'étudiant
alter table student_requests add column agent_note varchar(500);
